def _workday_count(url: str, company_check: str | None = None) -> tuple[int, str]:
    from backend.pipeline.direct import workday

    host, tenant, site = workday._parse_board_url(url)
    base = f"https://{host}/wday/cxs/{tenant}/{site}"
    resp = workday._SESSION.post(
        f"{base}/jobs", json={"appliedFacets": {}, "limit": 5, "offset": 0, "searchText": ""},
        timeout=20)
    data = workday._json(resp)
    postings = data.get("jobPostings") or []
    count = max(int(data.get("total") or 0), len(postings))
    if not company_check or not count:
        return count, ""
    # Shared tenant check: does a live job actually name the company?
    path = next((p.get("externalPath") for p in postings if p.get("externalPath")), None)
    if not path:
        return 0, f"no job to check for {company_check!r}"
    time.sleep(PAUSE_S)
    info = workday._json(workday._SESSION.get(f"{base}{path}", timeout=20)).get("jobPostingInfo") or {}
    hay = f"{info.get('externalUrl') or ''} {info.get('jobDescription') or ''}"
    if company_check.lower() not in hay.lower():
        return 0, f"job {path} does not mention {company_check!r}"
    return count, f"job {path} mentions {company_check!r} in its description/externalUrl"


def _oracle_count(url: str) -> tuple[int, str]:
    from backend.pipeline.direct import oracle

    host, site = oracle._parse_board_url(url)
    api = (f"https://{host}/hcmRestApi/resources/latest/recruitingCEJobRequisitions"
           f"?onlyData=true&expand=requisitionList&finder=findReqs;siteNumber={site},limit=5,offset=0")
    item = oracle._first_item(oracle._json(oracle._SESSION.get(api, timeout=20)), "list")
    reqs = item.get("requisitionList") or []
    return max(int(item.get("TotalJobsCount") or 0), len(reqs)), ""


def _oleeo_count(url: str) -> tuple[int, str]:
    from backend.pipeline.direct import FetchError, oleeo

    board = oleeo._clean_url(url)
    host = (urlparse(board).hostname or "").lower()
    if not host.endswith(".tal.net"):
        raise FetchError(f"unparseable Oleeo url: {url!r}")
    page = oleeo._get_html(board, "board")  # raises on captcha / non-tal.net
    return len(oleeo._vacancies(page, board, host)), "first page only"


def board_count(platform: str, url: str, company_check: str | None = None) -> tuple[int, str]:
    if platform == "workday":
        return _workday_count(url, company_check)
    if platform == "oracle":
        return _oracle_count(url)
    return _oleeo_count(url)


def discover_moelis_campus() -> str:
    """The Moelis campus job-board URL linked from its candidate landing page."""
    from backend.pipeline.direct import FetchError, oleeo

    page = oleeo._get_html(MOELIS_CAMPUS_LANDING, "moelis-campus landing")
    m = re.search(r'href="([^"]*/candidate/jobboard/vacancy/\d+/adv/?)"', page)
    if not m:
        raise FetchError("moelis-campus landing page links no job board")
    return oleeo._clean_url(urljoin(MOELIS_CAMPUS_LANDING, m.group(1)))


