def _unique_slug(slug: str, tenant: str, taken: set[str]) -> str:
    """`slug`, or `{slug}-{tenant}` (then `-2`, `-3`...) if already taken."""
    if slug and slug not in taken:
        return slug
    base = slugify(f"{slug}-{tenant}" if slug else tenant)
    cand, n = base, 2
    while cand in taken:
        cand, n = f"{base}-{n}", n + 1
    return cand


def build(listings: list[dict], employers: dict[str, str], validate=board_count,
          moelis_campus=discover_moelis_campus, log=print) -> dict:
    """Return {"rows": {platform: [row]}, "hot": [(platform, slug)], "dropped": [...]}.

    Rows are dicts {name, slug, url, analyst_entry, hot, jobs, note}."""
    rows: dict[str, list[dict]] = {p: [] for p in TARGET_PLATFORMS}
    dropped: list[dict] = []
    taken: dict[str, set[str]] = {p: set() for p in TARGET_PLATFORMS}

    def check(platform, slug, name, url, hot, company_check=None, match=""):
        time.sleep(PAUSE_S)
        try:
            count, note = validate(platform, url, company_check)
        except Exception as exc:  # one bad board never stops the build
            dropped.append({"platform": platform, "slug": slug, "name": name, "url": url,
                            "hot": hot, "reason": f"error: {exc}"[:200]})
            log(f"  DROP {platform}:{slug} ({name}) error: {exc}")
            return
        if count <= 0:
            dropped.append({"platform": platform, "slug": slug, "name": name, "url": url,
                            "hot": hot, "reason": note or "0 jobs"})
            log(f"  DROP {platform}:{slug} ({name}) {note or '0 jobs'}")
            return
        taken[platform].add(slug)
        rows[platform].append({"name": name, "slug": slug, "url": url,
                               "analyst_entry": analyst_entry(name), "hot": hot,
                               "jobs": count, "note": note, "match": match})
        log(f"  ok   {platform}:{slug} ({name}) {count} jobs {note}")

    from backend.pipeline.direct.workday import _parse_board_url

    log("Hand list:")
    hand_hosts = set()
    for platform, slug, name, url in HAND_LIST:
        if platform == "workday":
            hand_hosts.add(_parse_board_url(url)[0])
        check(platform, slug, name, url, True, COMPANY_CHECK.get(slug), match="hand list")
    try:
        mc_url = moelis_campus()
    except Exception as exc:
        dropped.append({"platform": "oleeo", "slug": "moelis-campus", "name": "Moelis & Company",
                        "url": MOELIS_CAMPUS_LANDING, "hot": True,
                        "reason": f"board URL not found: {exc}"[:200]})
        log(f"  DROP oleeo:moelis-campus board URL not found: {exc}")
    else:
        check("oleeo", "moelis-campus", "Moelis & Company", mc_url, True, match="hand list")

    tenants = simplify_workday_tenants(listings)
    targets, cold = [], []
    for host, t in sorted(tenants.items()):
        if host in hand_hosts:
            continue
        emp = match_large_employer(t["name"], employers)
        if emp and t["public_site"] and host not in FORCE_COLD:
            targets.append((host, t, emp))
        elif emp:
            why = FORCE_COLD.get(host) or "no public site"
            log(f"  cold target {host} ({t['name']}): {why}")
            cold.append((host, t, emp))
        elif t["active"] > 0:
            cold.append((host, t, ""))
    log(f"Simplify Workday tenants: {len(tenants)}; targets {len(targets)}; "
        f"cold candidates (>=1 active listing) {len(cold)}")

    for label, group, hot in (("Simplify targets:", targets, True), ("Simplify cold:", cold, False)):
        log(label)
        for host, t, emp in group:
            tenant = host.split(".")[0]
            slug = _unique_slug(slugify(t["name"]) or tenant, tenant, taken["workday"])
            check("workday", slug, t["name"], f"https://{host}/{t['site']}", hot,
                  match=f"large employer {emp!r}" if emp else "")

    hot = sorted((p, r["slug"]) for p in TARGET_PLATFORMS for r in rows[p] if r["hot"])
    return {"rows": rows, "hot": hot, "dropped": dropped}


def write_csvs(rows: dict[str, list[dict]], ats_dir: Path = ATS_DIR) -> None:
    for platform in TARGET_PLATFORMS:
        with (ats_dir / f"{platform}.csv").open("w", newline="") as f:
            w = csv.writer(f)
            w.writerow(["name", "slug", "url", "analyst_entry"])
            for r in sorted(rows[platform], key=lambda r: r["slug"]):
                w.writerow([r["name"], r["slug"], r["url"], r["analyst_entry"]])


def write_hot_slugs(rows: dict[str, list[dict]], path: Path = HOT_SLUGS) -> None:
    """Replace the target-platform lines of hot_slugs.txt; keep everything else."""
    keep = []
    for line in path.read_text().splitlines():
        head = line.strip().split(":", 1)[0].lower()
        if line.strip() == HOT_HEADER or head in TARGET_PLATFORMS:
            continue
        keep.append(line)
    while keep and not keep[-1].strip():
        keep.pop()
    lines = keep + ["", HOT_HEADER]
    for platform in TARGET_PLATFORMS:
        for r in sorted(rows[platform], key=lambda r: r["slug"]):
            if r["hot"]:
                lines.append(f"{platform}:{r['slug']}  # {r['name']}")
    path.write_text("\n".join(lines) + "\n")


def _load_listings(path: str | None) -> list[dict]:
    if path:
        return json.loads(Path(path).read_text())
    import requests

    from backend.pipeline.fetcher import SIMPLIFY_LISTINGS_URL

    resp = requests.get(SIMPLIFY_LISTINGS_URL, timeout=60)
    resp.raise_for_status()
    return resp.json()


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--dry-run", action="store_true", help="validate and print; write nothing")
    ap.add_argument("--listings", help="local copy of Simplify listings.json")
    ap.add_argument("--report", help="write the build result as JSON here")
    args = ap.parse_args()

    result = build(_load_listings(args.listings), load_large_employers())
    if args.report:
        Path(args.report).write_text(json.dumps(result, indent=2))
    for platform in TARGET_PLATFORMS:
        rs = result["rows"][platform]
        print(f"{platform}: {sum(r['hot'] for r in rs)} hot, {sum(not r['hot'] for r in rs)} cold")
    print(f"dropped: {len(result['dropped'])}")
    if args.dry_run:
        print("dry run: no files written")
        return
    write_csvs(result["rows"])
    write_hot_slugs(result["rows"])
    print(f"wrote {', '.join(f'{p}.csv' for p in TARGET_PLATFORMS)} and hot_slugs.txt in {ATS_DIR}")


if __name__ == "__main__":
    main()
