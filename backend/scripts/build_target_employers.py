# Some Simplify URLs carry a lowercase locale ("/en-us/External/...") that the
# Workday fetcher's parser would take for the site name; drop it.
_LOWER_LOCALE = re.compile(r"(myworkdayjobs\.com/)[a-z]{2}-[a-z]{2}/")


def slugify(name: str) -> str:
    """Company name -> our slug: `"J.P. Morgan Chase & Co."` -> `"jp-morgan-chase-co"`."""
    text = unicodedata.normalize("NFKD", name).encode("ascii", "ignore").decode()
    text = re.sub(r"[.'’]", "", text.lower())
    return re.sub(r"[^a-z0-9]+", "-", text).strip("-")


def normalize_name(name: str) -> str:
    """Comparable company name: lowercase words, & -> and, legal suffixes dropped."""
    text = unicodedata.normalize("NFKD", name).encode("ascii", "ignore").decode().lower()
    text = re.sub(r"[.'’]", "", text.replace("&", " and "))
    words = re.sub(r"[^a-z0-9]+", " ", text).split()
    if words and words[0] == "the":
        words = words[1:]
    while len(words) > 1 and (words[-1] in _LEGAL_SUFFIXES
                              or (words[-1] in _SOFT_SUFFIXES and len(words) > 2)):
        words.pop()
    return " ".join(words)


def _words(name: str) -> str:
    text = unicodedata.normalize("NFKD", name).encode("ascii", "ignore").decode().lower()
    text = re.sub(r"[.'\u2019]", "", text.replace("&", " and "))
    return " " + " ".join(re.sub(r"[^a-z0-9]+", " ", text).split()) + " "


def analyst_entry(name: str) -> int:
    """1 for banks, asset managers, PE/hedge funds, exchanges, insurers with
    analyst programs and the Big 4; else 0."""
    if ANALYST_ENTRY_RE.search(name):
        return 1
    words = _words(name)
    return 1 if any(f" {fin} " in words for fin in FINANCE_NAMES) else 0


def load_large_employers(path: Path = LARGE_EMPLOYERS) -> dict[str, str]:
    """normalized name -> original name."""
    out: dict[str, str] = {}
    for raw in path.read_text().splitlines():
        line = raw.strip()
        if line and not line.startswith("#"):
            out.setdefault(normalize_name(line), line)
    return out


def match_large_employer(name: str, employers: dict[str, str]) -> str | None:
    """The large-employer name this company matches: same normalized name, or
    the employer's name followed only by generic words ("Gilead Sciences" ->
    "Gilead", "Truist Bank" -> "Truist")."""
    norm = normalize_name(name)
    if norm in REJECT_NAMES:
        return None
    if norm in employers:
        return employers[norm]
    for emp_norm, emp in employers.items():
        if norm.startswith(emp_norm + " ") and set(norm[len(emp_norm):].split()) <= _GENERIC_WORDS:
            return emp
    return None


def simplify_workday_tenants(listings: list[dict]) -> dict[str, dict]:
    """host -> {name, site, active} for Workday tenants in Simplify listings."""
    from backend.pipeline.direct import FetchError
    from backend.pipeline.direct.workday import _parse_board_url

    names: dict[str, Counter] = defaultdict(Counter)
    sites: dict[str, Counter] = defaultdict(Counter)
    active: Counter = Counter()
    for item in listings:
        url = _LOWER_LOCALE.sub(r"\1", item.get("url") or "", count=1)
        try:
            host, _tenant, site = _parse_board_url(url)
        except FetchError:
            continue
        name = (item.get("company_name") or "").strip()
        if name:
            names[host][name] += 1
        is_active = bool(item.get("active"))
        sites[host][site] += 2 if is_active else 1  # prefer the live site
        active[host] += int(is_active)
    out = {}
    for host in sites:
        if not names[host]:
            continue
        public = [s for s, _ in sites[host].most_common() if not SITE_DENY_RE.search(s)]
        site = SITE_OVERRIDES.get(host) or (public[0] if public else sites[host].most_common(1)[0][0])
        out[host] = {"name": names[host].most_common(1)[0][0], "site": site,
                     "active": active[host], "public_site": bool(SITE_OVERRIDES.get(host) or public)}
    return out


